import assert from "node:assert/strict";
import fs from "node:fs";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const hub=require("./live-hub.js");
const source=fs.readFileSync(new URL("./live-hub.js",import.meta.url),"utf8");
let calls=0;
const failed=await hub.safePersonalSync({async sync(){calls++;throw new Error("LAB participation service unavailable")}});
assert.deepEqual(failed,{ok:false,items:[]});
assert.equal(calls,1);
const successful=await hub.safePersonalSync({async sync(){return{ok:true,items:[{token:"personal_tournament"}]}}});
assert.equal(successful.ok,true);
assert.equal(successful.items.length,1);
const token="directory_production_36c43fd8-594e-40e3-af6d-13bfd1863f20";
assert.equal(hub.resolveDirectoryEventToken(token,[]),token,"a valid invitation ID must open Scores even when the directory list is empty or unavailable");
assert.equal(hub.resolveDirectoryEventToken(token,[{token}]),token,"a listed event keeps its original selection path");
assert.equal(hub.resolveDirectoryEventToken("directory_production_invalid",[]),"","an invalid directory token must never trigger a read");
const start=source.slice(source.indexOf("async function start()"));
assert.ok(start.indexOf("const personal=await safePersonalSync")>0,"startup must treat membership lookup as recoverable");
assert.ok(start.indexOf("resolveDirectoryEventToken(params.get('directoryEvent'),registeredDirectory)")>start.indexOf("const personal=await safePersonalSync"),"startup must resolve the invitation ID even if no directory entry loaded");
assert.match(source,/directoryView\|\|joined\|\|/,"federated Scores must not show a misleading participant-membership warning");
console.log("PASS R174: rejected local membership is recoverable and a valid invitation ID opens Scores without a populated tournament list.");
