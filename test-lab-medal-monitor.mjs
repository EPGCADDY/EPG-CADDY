import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const hub=createRequire(import.meta.url)('./live-hub.js');
const source=fs.readFileSync('live-hub.js','utf8');
const stream=(id,count)=>({id,groupLabel:id,snapshot:{mode:'general',players:[{id,name:id,holes:Array.from({length:count},(_,i)=>({hole:i+1,gross:4,net:4,par:4,relativeToPar:0}))}]}});
const streams=new Map([['a',stream('A',3)],['b',stream('B',9)],['c',stream('C',6)]]);
const rows=hub.buildLeaderboard(streams,false);
assert.deepEqual(rows.map(p=>p.name),['B','C','A']);
const wrap={innerHTML:'',querySelectorAll:()=>[]};
const context={$:()=>wrap,buildLeaderboard:()=>rows,displayStreams:()=>streams,state:{follows:[]},escapeHtml:String,categoryShortLabel:()=>'',modeLabel:()=> 'MEDAL PLAY NORMAL',relation:n=>n===0?'EVEN':String(n)};
vm.runInNewContext(source.slice(source.indexOf('  function renderLeaderboard(){'),source.indexOf('  function categoryCell('))+';renderLeaderboard()',context);
for(const title of ['HOYO ACTUAL','GROSS','NETO','RESULTADO'])assert.ok(wrap.innerHTML.includes('<th>'+title+'</th>'));
assert.ok(!wrap.innerHTML.includes('<th>PUNTOS</th>'));
for(const title of ['GRUPO','MODALIDAD'])assert.ok(!wrap.innerHTML.includes('<th>'+title+'</th>'));
for(const title of ['CATEGORÍA','SEGUIR'])assert.ok(wrap.innerHTML.includes('<th>'+title+'</th>'));
const live=fs.readFileSync('live-control.js','utf8');const status={dataset:{}};
const ctx={$:()=>status,foregroundStatus:false};
vm.runInNewContext(live.slice(live.indexOf('  function setStatus('),live.indexOf('  function stateMessage('))+';setStatus("FALLO TORNEO","warning");setStatus("EN VIVO","ok",true)',ctx);
assert.equal(status.textContent,'FALLO TORNEO');
console.log('PASS Medal: columnas correctas, sin puntos, empate por avance; error de acción conserva visibilidad');
