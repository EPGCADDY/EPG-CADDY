import fs from "node:fs";
import assert from "node:assert/strict";
const app=fs.readFileSync("index-grupal.html","utf8");
const sw=fs.readFileSync("service-worker.js","utf8");
const release=JSON.parse(fs.readFileSync("release.json","utf8"));
const appRelease=(app.match(/name="gscg-release" content="([^"]+)"/)||[])[1];
assert.equal(appRelease,release.release,"APP and release.json must publish the same release");
assert.match(sw,/fetchPublishedRelease\(\)/,"Service Worker must resolve release dynamically");
assert.match(sw,/fetch\("\/release\.json\?sw_release_check="/,"Service Worker must bypass cached release metadata");
assert.match(sw,/url\.pathname==="\/release\.json"[^\n]*cache:"no-store"/,"release.json must bypass Service Worker cache");
assert.doesNotMatch(sw,/const RELEASE="(?:LABORATORIO|PRODUCTION)-/,"Service Worker release must never be hard-coded again");
assert.match(sw,/ACTIVE_CACHE_NAME=`\$\{CACHE_NAME\}-active-[^`]+`/,"Every rescue publication must use a fresh active cache namespace");
assert.match(sw,/APPROVED_CACHE_NAME=`\$\{CACHE_NAME\}-approved-[^`]+`/,"Every rescue publication must use a fresh approved cache namespace");
console.log("PASS RELEASE MATRIX: app/release aligned; updater is release-independent and future-version safe");

const updater=fs.readFileSync("app-update.js","utf8");
assert.match(updater,/GET_APPROVED_RELEASE/,"Updater must identify its controlling approved worker");
assert.match(updater,/update_return/,"Administration update must retain return route");
assert.ok(sw.includes('destination.pathname==="/event-administration.html"'),"Worker must restrict update return to Administration");
assert.match(fs.readFileSync("RELEASE_UPDATE_MATRIX.md","utf8"),/Paridad obligatoria LAB \/ Producción/);
assert.ok(fs.existsSync("scripts/deployment-parity-gate.mjs"),"Mandatory served-content parity gate is required");
