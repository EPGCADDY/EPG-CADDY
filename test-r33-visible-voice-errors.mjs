import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('index-grupal.html','utf8');
const elements=new Map(),positions=[];
const classes={toggle(){}};
for(const id of ['aiUniversalState','setupVoiceMatrix','status','toolbar'])elements.set(id,{id,textContent:'',classList:classes,insertAdjacentElement(position,el){elements.set(el.id,el);positions.push({anchor:id,position})}});
const env=vm.createContext({voiceContext:'round',$:id=>elements.get(id),window:{},document:{querySelector:()=>elements.get('toolbar'),createElement:()=>({style:{},setAttribute(key,value){this[key]=value},remove(){elements.delete(this.id)}})}});
vm.runInContext(html.slice(html.indexOf('function showUniversalVoiceNotice('),html.indexOf('function aiUniversalRemember(')),env);
env.aiUniversalSetState('NO HAY UN MICRÓFONO DISPONIBLE EN ESTE DISPOSITIVO');
assert.equal(elements.get('universalVoiceNotice').role,'alert');
assert.equal(positions.at(-1).anchor,'toolbar');
elements.get('status').textContent='INICIO 11:16 p. m.';
assert.match(elements.get('universalVoiceNotice').textContent,/NO HAY UN MICRÓFONO/,'El reloj no puede borrar el error');
env.aiUniversalSetState('ESCUCHANDO',{busy:true});assert.equal(elements.has('universalVoiceNotice'),false);
env.voiceContext='setup';env.aiUniversalSetState('VOZ MASCULINA NO DISPONIBLE · INTENTA DE NUEVO');
assert.equal(positions.at(-1).anchor,'setupVoiceMatrix');
assert.match(elements.get('universalVoiceNotice').textContent,/NO DISPONIBLE/);
env.showUniversalVoiceNotice('<img src=x onerror=alert(1)>');
assert.equal(elements.get('universalVoiceNotice').textContent,'<img src=x onerror=alert(1)>');
assert.equal(elements.get('universalVoiceNotice').innerHTML,undefined);
console.log('PASS R33 · aviso visible en tarjeta/registro, independiente del reloj, limpieza al reintentar y texto seguro');
